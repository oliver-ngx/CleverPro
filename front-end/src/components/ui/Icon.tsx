function isRaster(name: IconName): name is RasterName {
  return name in RASTER_GLYPHS
}

interface IconProps {
  name: IconName
  /** Tailwind sizing/colour classes. Every call site sizes the glyph explicitly. */
  className?: string
}

export function Icon({ name, className }: IconProps) {
  if (isRaster(name)) {
    return (
      <img src={RASTER_GLYPHS[name]} alt="" className={`object-contain ${className ?? ''}`} />
    )
  }

  const glyph = VECTOR_GLYPHS[name]
  return (
    <svg viewBox={glyph.viewBox} fill="none" aria-hidden="true" className={className}>
      {glyph.body}
    </svg>
  )
}
