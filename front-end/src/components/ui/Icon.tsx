function isRaster(name: IconName): name is RasterName {
  return name in RASTER_GLYPHS
}

interface IconProps {
  name: IconName
  /** Tailwind sizing/colour classes. Every call site sizes the glyph explicitly. */
  className?: string
  /** For the few sizes that come from data rather than from a class. */
  style?: CSSProperties
}

/**
 * Memoised because almost every screen is mostly glyphs: a state change anywhere in
 * App walks fifty-odd of these, and a glyph can only have changed if its name or its
 * classes did. The few call sites that size a glyph from data pass a fresh `style`
 * object and so re-render anyway, which is correct — that object is what changed.
 */
export const Icon = memo(function Icon({ name, className, style }: IconProps) {
  if (isRaster(name)) {
    return (
      <img
        src={RASTER_GLYPHS[name]}
        alt=""
        style={style}
        className={`object-contain ${className ?? ''}`}
      />
    )
  }

  const glyph = VECTOR_GLYPHS[name]
  return (
    <svg viewBox={glyph.viewBox} fill="none" aria-hidden="true" style={style} className={className}>
      {glyph.body}
    </svg>
  )
})
